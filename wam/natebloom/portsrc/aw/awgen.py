#!/usr/bin/env python3
"""awgen.py NAME → aw_NAME.h: an Airwindows plugin (MIT) as a plain C++ struct for the WebAssembly ports.
Takes the member variables from NAME.h, the constructor's body from NAME.cpp and processReplacing from NAMEProc.cpp,
unchanged but for: the VST plumbing dropped, getSampleRate() from the struct, and the float version only."""
import re, sys, os
name = sys.argv[1]
SRC = "/tmp/claude-0/src5/airwindows/plugins/LinuxVST/src/" + name
h = open(f"{SRC}/{name}.h").read(); c = open(f"{SRC}/{name}.cpp").read(); p = open(f"{SRC}/{name}Proc.cpp").read()

pre = h[h.index("kNumParameters"):]
pre = pre[pre.index("}") + 1:pre.index("class " + name)]
pre = "\n".join(l for l in pre.split("\n") if re.match(r"\s*(const int|const double|static const)", l) and not re.search(r"kNum|kUnique", l))
priv = h[h.index("private:") + 8:]
priv = priv[:priv.rindex("};")]
priv = "\n".join(l for l in priv.split("\n") if "_programName" not in l and "_canDo" not in l)

def body_of(src, sig_re):
    m = re.search(sig_re, src); assert m, sig_re
    i = src.index("{", m.end() - 1); depth = 0
    for j in range(i, len(src)):
        if src[j] == "{": depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0: return src[i + 1:j]
ctor = body_of(c, name + r"::" + name + r"\s*\(audioMasterCallback audioMaster\)\s*:[^{]*\{")
ctor = "\n".join(l for l in ctor.split("\n") if not re.search(r"setNumInputs|setNumOutputs|setUniqueID|canProcessReplacing|canDoubleReplacing|programsAreChunks|vst_strncpy|_canDo|_programName|^\s*//", l))
proc = body_of(p, r"void " + name + r"::processReplacing\(float \*\*inputs, float \*\*outputs, VstInt32 sampleFrames\)\s*\{")

out = f"""// Airwindows {name} (Chris Johnson, MIT), generated by awgen.py from plugins/LinuxVST/src/{name}: the member
// variables, the constructor and processReplacing as they are, with the VST host plumbing taken out.
#pragma once
#include <math.h>
#include <stdint.h>
#include <stdlib.h>
typedef int32_t VstInt32;
namespace aw_{name} {{
{pre}
struct AW_{name} {{
  double sr_ = 44100;
  double getSampleRate() {{ return sr_; }}
  float A = 0, B = 0, C = 0, D = 0, E = 0, F = 0, G = 0, H = 0, I = 0, J = 0;
{priv}
  void init(double sr) {{
    sr_ = sr;
{ctor}
  }}
  void processReplacing(float **inputs, float **outputs, VstInt32 sampleFrames) {{
{proc}
  }}
}};
}}
using aw_{name}::AW_{name};
"""
# members the header declares as float A, B…: drop our defaults if they clash
for v in "ABCDEFGHIJ":
    if re.search(r"\bfloat\s+" + v + r"\s*;", priv) or re.search(r"\bdouble\s+" + v + r"\s*;", priv):
        out = out.replace(f" {v} = 0,", "").replace(f", {v} = 0;", ";")
out = re.sub(r"float\s*;", "", out)
# the float dither at the end (Web Audio is floating point all the way): dropped, as in the Galactic port
out = "\n".join(l for l in out.split("\n") if "frexpf" not in l and "5.5e-36l" not in l and "begin 32 bit floating point dither" not in l and "end 32 bit floating point dither" not in l)
os.makedirs("/tmp/claude-0/port/aw", exist_ok=True)
open(f"/tmp/claude-0/port/aw/aw_{name}.h", "w").write(out)
print(name, len(out.split("\n")), "lines")
