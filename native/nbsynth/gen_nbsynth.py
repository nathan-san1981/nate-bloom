#!/usr/bin/env python3
"""Nathan's plugin instruments as native code for the apps' fast audio: each wam/natebloom/<id>/dsp.wasm through
wasm2c (the same DSP the web app runs, as C), plus nbsynth.c, one small C API over all of them.
usage: gen_nbsynth.py WASM2C WAMDIR OUTDIR"""
import os, re, subprocess, sys
W2C, WAM, OUT = sys.argv[1:4]
IDS = ["twin77", "duet80", "nebula80", "hypnagogia", "parafour", "stab85", "pop89", "unicorn_dream", "fuzz_bass", "ballad_kit"]   # the instruments (Glitch Starter is an effect)
os.makedirs(OUT, exist_ok=True)
mods = []
for pid in IDS:
    m = pid.replace("_", "")
    subprocess.run([W2C, os.path.join(WAM, pid, "dsp.wasm"), "--module-name=" + m, "-o", os.path.join(OUT, m + ".c")], check=True)
    h = open(os.path.join(OUT, m + ".h")).read()
    has = lambda f: ("w2c_%s_%s(" % (m, f)) in h
    env = ("wasm2c_%s_instantiate(w2c_%s*, struct w2c_env*)" % (m, m)) in h
    mods.append(dict(id=pid, m=m, env=env, ctors=has("0x5F_wasm_call_ctors"), tempo=has("nb_tempo"), reset=has("nb_reset")))
c = ['''// Generated by gen_nbsynth.py: Nathan's plugin instruments (wasm2c output alongside) behind one C API.
#include <math.h>
#include <string.h>
#include "wasm-rt-impl.h"
#include "wasm-rt-exceptions.h"
#include "nbsynth.h"
''']
for d in mods: c.append('#include "%s.h"\n' % d["m"])
c.append('''
struct w2c_env { int unused; };
f64 w2c_env_sin(struct w2c_env* e, f64 x) { (void) e; return sin(x); }
static struct w2c_env g_env;

typedef struct {
  const char* id;
  int made, alive;
  void (*make)(void);
  wasm_rt_memory_t* (*mem)(void);
  void (*init)(float);
  unsigned (*params)(void);
  unsigned (*count)(void);
  void (*midi)(unsigned, unsigned, unsigned);
  void (*render)(unsigned);
  unsigned (*out)(unsigned);
  void (*tempo)(double, unsigned);
  void (*reset)(void);
} Plug;
''')
for d in mods:
    m = d["m"]; I = "&i_" + m
    c.append('static w2c_%s i_%s;\n' % (m, m))
    c.append('static void mk_%s(void) { wasm2c_%s_instantiate(%s%s); %s }\n' % (m, m, I, ", &g_env" if d["env"] else "", ("w2c_%s_0x5F_wasm_call_ctors(%s);" % (m, I)) if d["ctors"] else ""))
    c.append('static wasm_rt_memory_t* mem_%s(void) { return w2c_%s_memory(%s); }\n' % (m, m, I))
    c.append('static void init_%s(float r) { w2c_%s_nb_init(%s, r); }\n' % (m, m, I))
    c.append('static unsigned params_%s(void) { return w2c_%s_nb_params(%s); }\n' % (m, m, I))
    c.append('static unsigned count_%s(void) { return w2c_%s_nb_count(%s); }\n' % (m, m, I))
    c.append('static void midi_%s(unsigned a, unsigned b, unsigned d) { w2c_%s_nb_midi(%s, a, b, d); }\n' % (m, m, I))
    c.append('static void render_%s(unsigned n) { w2c_%s_nb_render(%s, n); }\n' % (m, m, I))
    c.append('static unsigned out_%s(unsigned ch) { return w2c_%s_nb_out(%s, ch); }\n' % (m, m, I))
    c.append(('static void tempo_%s(double b, unsigned p) { w2c_%s_nb_tempo(%s, b, p); }\n' % (m, m, I)) if d["tempo"] else 'static void tempo_%s(double b, unsigned p) { (void) b; (void) p; }\n' % m)
    c.append(('static void reset_%s(void) { w2c_%s_nb_reset(%s); }\n' % (m, m, I)) if d["reset"] else 'static void reset_%s(void) {}\n' % m)
c.append('static Plug g_plugs[] = {\n')
for d in mods:
    m = d["m"]
    c.append('  { "%s", 0, 0, mk_%s, mem_%s, init_%s, params_%s, count_%s, midi_%s, render_%s, out_%s, tempo_%s, reset_%s },\n' % (d["id"], m, m, m, m, m, m, m, m, m, m))
c.append('};\n')
c.append('''#define N_PLUGS ((int) (sizeof(g_plugs) / sizeof(g_plugs[0])))
static int g_rt = 0;

int nbs_count(void) { return N_PLUGS; }
const char* nbs_id(int i) { return i >= 0 && i < N_PLUGS ? g_plugs[i].id : ""; }
int nbs_find(const char* id) { for (int i = 0; i < N_PLUGS; i++) if (!strcmp(g_plugs[i].id, id)) return i; return -1; }
void nbs_thread_init(void) { if (g_rt) wasm_rt_init_thread(); }

// Make the instrument (once) and start it at this sample rate. Not on the audio thread.
int nbs_create(int i, float rate) {
  if (i < 0 || i >= N_PLUGS) return 0;
  Plug* p = &g_plugs[i];
  if (!g_rt) { wasm_rt_init(); g_rt = 1; }
  if (wasm_rt_impl_try() != 0) { p->alive = 0; return 0; }
  if (!p->made) { p->make(); p->made = 1; }
  p->init(rate);
  p->alive = 1;
  return 1;
}
int nbs_alive(int i) { return i >= 0 && i < N_PLUGS && g_plugs[i].alive; }
int nbs_params(int i) { if (!nbs_alive(i)) return 0; return (int) g_plugs[i].count(); }
void nbs_param(int i, int idx, float v) {
  if (!nbs_alive(i)) return;
  Plug* p = &g_plugs[i];
  if (idx < 0 || idx >= (int) p->count()) return;
  wasm_rt_memory_t* m = p->mem(); unsigned at = p->params() + 4u * (unsigned) idx;
  if ((uint64_t) at + 4 <= m->size) memcpy(m->data + at, &v, 4);
}
void nbs_midi(int i, int st, int d1, int d2) {
  if (!nbs_alive(i)) return;
  if (wasm_rt_impl_try() != 0) { g_plugs[i].alive = 0; return; }
  g_plugs[i].midi((unsigned) st, (unsigned) d1, (unsigned) d2);
}
void nbs_tempo(int i, double bpm, int playing) {
  if (!nbs_alive(i)) return;
  if (wasm_rt_impl_try() != 0) { g_plugs[i].alive = 0; return; }
  g_plugs[i].tempo(bpm, (unsigned) playing);
}
void nbs_reset(int i) {
  if (!nbs_alive(i)) return;
  if (wasm_rt_impl_try() != 0) { g_plugs[i].alive = 0; return; }
  g_plugs[i].midi(0xB0, 64, 0); g_plugs[i].midi(0xB0, 120, 0); g_plugs[i].reset();
}
// n frames (at most 512) into L and R; 0 if the instrument stopped (it trapped)
int nbs_render(int i, int n, float* L, float* R) {
  if (!nbs_alive(i) || n <= 0) return 0;
  Plug* p = &g_plugs[i];
  if (n > 512) n = 512;
  if (wasm_rt_impl_try() != 0) { p->alive = 0; return 0; }
  p->render((unsigned) n);
  wasm_rt_memory_t* m = p->mem(); unsigned a = p->out(0), b = p->out(1);
  if ((uint64_t) a + 4u * n > m->size || (uint64_t) b + 4u * n > m->size) { p->alive = 0; return 0; }
  memcpy(L, m->data + a, 4u * (unsigned) n); memcpy(R, m->data + b, 4u * (unsigned) n);
  return 1;
}
''')
open(os.path.join(OUT, "nbsynth.c"), "w").write("".join(c))
open(os.path.join(OUT, "nbsynth.h"), "w").write('''// Nathan's plugin instruments, native: a small C API over the wasm2c builds (see nbsynth.c).
#ifndef NBSYNTH_H
#define NBSYNTH_H
#ifdef __cplusplus
extern "C" {
#endif
int nbs_count(void);
const char* nbs_id(int i);
int nbs_find(const char* id);
void nbs_thread_init(void);
int nbs_create(int i, float rate);
int nbs_alive(int i);
int nbs_params(int i);
void nbs_param(int i, int idx, float v);
void nbs_midi(int i, int st, int d1, int d2);
void nbs_tempo(int i, double bpm, int playing);
void nbs_reset(int i);
int nbs_render(int i, int n, float* L, float* R);
#ifdef __cplusplus
}
#endif
#endif
''')
print("generated", len(mods), "instruments:", ", ".join(d["id"] for d in mods))
